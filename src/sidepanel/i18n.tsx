const dictionaries: Record<AppLocale, Record<TranslationKey, string>> = {
  'zh-TW': zhTW,
  en,
  ja,
  'zh-CN': zhCN,
};

function interpolate(template: string, values?: Record<string, string | number>): string {
  if (!values) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    values[key] === undefined ? match : String(values[key]),
  );
}

interface I18nValue {
  locale: AppLocale;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue>({
  locale: 'zh-TW',
  t: (key, values) => interpolate(zhTW[key], values),
});

export function I18nProvider({ locale, children }: { locale: AppLocale; children: ReactNode }) {
  const value = useMemo<I18nValue>(() => ({
    locale,
    t: (key, values) => interpolate(dictionaries[locale][key], values),
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
